def _split_csv(value: str | None) -> list[str]:
    if not value:
        return []
    cleaned: list[str] = []
    for raw in value.split(","):
        v = (raw or "").strip()
        if not v:
            continue
        if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"', "`"):
            v = v[1:-1].strip()
        if v:
            cleaned.append(v)
    return cleaned

