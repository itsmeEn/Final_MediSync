def _ensure_url_scheme(value: str) -> str:
    v = (value or "").strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"', "`"):
        v = v[1:-1].strip()
    if not v:
        return v
    if "://" in v:
        return v
    return f"https://{v}"

def _origin_from_url(value: str) -> str:
    v = _ensure_url_scheme(value)
    try:
        p = urlparse(v)
        if not p.scheme or not p.netloc:
            return ""
        return f"{p.scheme}://{p.netloc}"
    except Exception:
        return ""

